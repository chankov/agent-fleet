export function selectFullTestFiles() {
  // The fast lane and the standalone TTY phase already cover these files in
  // the default environment. The guarded lanes and CLI smoke tests run separately.
  const covered = new Set([...fastTestFiles, "bin/test/setup-tty.test.js"]);
  const files = new Set(fullTestPatterns.flatMap(pattern => {
    const matches = globSync(pattern, { cwd: root }).sort();
    if (matches.length === 0) throw new Error(`No full-lane tests match ${pattern}`);
    return matches;
  }));
  return [...files].filter(file => !covered.has(file));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = selectFullTestFiles();
  // These fixtures give npm pack a fixed subprocess budget. Keep them away
  // from the other tarball builders so they do not compete for disk bandwidth.
  const boundedTarballTests = new Set([
    "bin/test/context-continuity-installed.test.js",
    "bin/test/proactive-installed.test.js",
  ]);
  const phases = [
    { name: "bounded tarball integrations", concurrency: 1, files: files.filter(file => boundedTarballTests.has(file)) },
    // AF_TEST_CONCURRENCY lowers (or raises) this phase only; the default is 4.
    { name: "remaining default-environment tests", concurrency: configuredConcurrency(), files: files.filter(file => !boundedTarballTests.has(file)) },
  ];
  for (const phase of phases) {
    if (phase.files.length === 0) continue;
    console.log(`Full lane phase: ${phase.name} (${phase.files.length} files, concurrency ${phase.concurrency})`);
    const result = spawnSync(process.execPath, ["--test", `--test-concurrency=${phase.concurrency}`, "--test-timeout=120000", ...phase.files], {
      cwd: root,
      stdio: "inherit",
    });
    if (result.error) throw result.error;
    if (result.status !== 0) {
      process.exitCode = result.status ?? 1;
      break;
    }
  }
}
